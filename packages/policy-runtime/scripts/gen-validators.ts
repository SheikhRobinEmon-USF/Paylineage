/**
 * Precompile the policy input and output JSON Schemas into plain JS (Ajv standalone).
 * Browsers run a strict CSP without 'unsafe-eval', so runtime schema compilation is
 * not allowed there. Run: node packages/policy-runtime/scripts/gen-validators.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = resolve(import.meta.dirname, "../../..");
const read = (p: string): Record<string, unknown> => JSON.parse(readFileSync(join(root, p), "utf8")) as Record<string, unknown>;
const input = read("policy/schema/input.v1.json");
const output = read("policy/schema/output.v1.json");
const ajv = new Ajv2020({ code: { source: true, esm: true, lines: false }, strict: true, strictRequired: false, strictTypes: false });
ajv.addSchema(input);
ajv.addSchema(output);
const code = (standaloneCode as unknown as (a: unknown, refs: Record<string, string>) => string)(ajv, {
  validateInput: String(input["$id"]),
  validateOutput: String(output["$id"]),
});
// Self contained: replace Ajv runtime requires with local helpers (no imports, no eval).
const helpers = `
function __ucs2length(str) { let n = 0; for (const _ of str) n++; return n; }
function __equal(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    if (Array.isArray(a) !== Array.isArray(b)) return false;
    if (Array.isArray(a)) return a.length === b.length && a.every((x, i) => __equal(x, b[i]));
    const ka = Object.keys(a), kb = Object.keys(b);
    return ka.length === kb.length && ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && __equal(a[k], b[k]));
  }
  return a !== a && b !== b;
}
`;
const body = code
  .replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, "__ucs2length")
  .replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g, "__equal");
if (body.includes("require(")) throw new Error("unexpected require in generated validators");
const header = "// GENERATED by packages/policy-runtime/scripts/gen-validators.ts from policy/schema. Do not edit.\n// @ts-nocheck\n/* eslint-disable */\n";
writeFileSync(resolve(import.meta.dirname, "../src/validators.gen.js"), header + helpers + body.replace(/^"use strict";/, ""));
console.log("wrote src/validators.gen.js");
