"""Build policy/dist/policy.wasm and policy.sha256 reproducibly (T0.3).

Steps:
  1. Stage Rego sources plus a generated `config` package compiled from
     policy/data/config.v1.json. Data is embedded in the Wasm module, so one
     SHA-256 identifies policy and data together.
  2. Run the pinned OPA binary: opa build -t wasm -e paylineage/decision.
  3. Extract policy.wasm, refuse modules that import host built-ins, write the hash.

Usage: python policy/scripts/build.py [--stage-only] [--opa PATH]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STAGE = ROOT / "build" / "stage"
DIST = ROOT / "dist"
ENTRYPOINT = "paylineage/decision"


def generated_config_rego(config: dict[str, object]) -> str:
    lines = [
        "# GENERATED by policy/scripts/build.py from policy/data/config.v1.json. Do not edit.",
        "package config",
        "",
    ]
    for key in sorted(config):
        if not key.isidentifier():
            raise SystemExit(f"config key is not a valid identifier: {key!r}")
        lines.append(f"{key} := {json.dumps(config[key], sort_keys=True)}")
        lines.append("")
    return "\n".join(lines)


def stage() -> Path:
    if STAGE.exists():
        shutil.rmtree(STAGE)
    (STAGE / "paylineage").mkdir(parents=True)
    for src in sorted((ROOT / "paylineage").glob("*.rego")):
        shutil.copy2(src, STAGE / "paylineage" / src.name)
    raw = json.loads((ROOT / "data" / "config.v1.json").read_text())
    (STAGE / "config.rego").write_text(generated_config_rego(raw["config"]))
    return STAGE


def required_opa_version() -> str:
    return (ROOT / "OPA_VERSION").read_text().strip()


def check_opa(opa: str) -> None:
    out = subprocess.run([opa, "version"], check=True, capture_output=True, text=True).stdout
    first = out.splitlines()[0]
    want = required_opa_version()
    if first.strip() != f"Version: {want}":
        raise SystemExit(f"OPA version mismatch: need {want}, found {first!r}. Run make setup.")


def build(opa: str) -> str:
    check_opa(opa)
    staged = stage()
    bundle = ROOT / "build" / "bundle.tar.gz"
    subprocess.run(
        [opa, "build", "-t", "wasm", "-e", ENTRYPOINT, "-O=1", str(staged), "-o", str(bundle)],
        check=True,
        cwd=ROOT,
    )
    with tarfile.open(bundle, "r:gz") as tar:
        member = tar.getmember("/policy.wasm")
        fh = tar.extractfile(member)
        if fh is None:
            raise SystemExit("bundle has no policy.wasm")
        wasm = fh.read()
    DIST.mkdir(exist_ok=True)
    (DIST / "policy.wasm").write_bytes(wasm)
    digest = hashlib.sha256(wasm).hexdigest()
    (DIST / "policy.sha256").write_text(f"{digest}  policy.wasm\n")
    return digest


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage-only", action="store_true")
    ap.add_argument("--opa", default=shutil.which("opa") or "opa")
    args = ap.parse_args()
    if args.stage_only:
        print(stage())
        return 0
    digest = build(args.opa)
    print(f"policy.wasm sha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
